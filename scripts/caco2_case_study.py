PROXY_OFFSET = 0.8
LOGP_THRESHOLD = 3.0
PRACTICAL_IMPROVEMENT = 0.02


def case_protocol(*, fixture=False):
    rules = resolve_protocol("plb://tdc/admet/caco2-wang@1.0.0").as_dict()
    rules["id"] = (
        "plb://tests/caco2-case"
        if fixture
        else "plb://examples/caco2-external-validation"
    )
    rules["uncertainty"].update(
        enabled=True, resamples=100 if fixture else 1000, include_slices=True
    )
    rules["comparison"].update(
        resamples=100 if fixture else 1000,
        permutations=0,
        practical_threshold=PRACTICAL_IMPROVEMENT,
        include_slice_uncertainty=True,
    )
    rules["slices"] = {"required": ["regime"], "optional": [], "min_size": 5}
    rules["sampling_design"] = SamplingDesign.from_dict(
        {
            "schema_version": "sampling-design/v1",
            "unit": "molecule_connectivity",
            "method": "cluster_bootstrap",
            "cluster_columns": ["molecule_unit"],
            "min_independent_units": 20,
            "exchangeability": "none",
        }
    ).as_dict()
    rules["evaluation_design"] = EvaluationDesign.from_dict(
        {
            "schema_version": "evaluation-design/v1",
            "unit": "molecule_connectivity",
            "entity_columns": ["molecule_unit"],
            "label_column": None,
            "repeated_entities": "allow",
            "exclusions": [
                {
                    "column": "eligible",
                    "operator": "equals",
                    "value": False,
                    "reason": "training_overlap_ineligible",
                }
            ],
        }
    ).as_dict()
    rules["quality_gate"] = {
        "schema_version": "quality-policy/v1",
        "metric": {"mae": {"max": 0.6, "max_ci_upper": 0.7}},
        "slices": {
            "critical": {
                "high_logp": {
                    "column": "regime",
                    "value": "high-logp",
                    "metric": "mae",
                    "max": 0.7,
                }
            }
        },
    }
    rules["release"].update(
        id="case-study-v1", require_privacy_audit=False, require_design_audit=True
    )
    return EvaluationProtocol.from_dict(rules)


def _model_info(folder, name, payload):
    path = folder / (name + ".json")
    path.write_text(
        json.dumps(payload, sort_keys=True, allow_nan=False) + "\n", encoding="utf-8"
    )
    return {
        "id": name,
        "revision": "reference-v1",
        "artifact_sha256": sha256(path.read_bytes()).hexdigest(),
    }


def _context(model, provenance, cohort):
    return {
        "schema_version": "external-validation-profile/v1",
        "model": model,
        "dataset": {
            "visibility": "public",
            "training_overlap": "none_known",
            "provenance_statement": provenance["description"] + " Cohort: " + cohort,
        },
        "evaluator_relationship": "model_developer",
        "relationship_statement": "Controlled reference models generated by this example; no independent/clinical validation claim.",
    }


def _release(context):
    return {
        "schema_version": "release-policy/v1",
        "id": "reviewed-caco2-case-v1",
        "enabled": True,
        "require_privacy_audit": False,
        "require_design_audit": True,
        "include_protocol": True,
        "include_design_audit": True,
        "include_quality_gate": True,
        "include_slice_inference": True,
        "include_degradation": True,
        "public_shift_features": ["target", "prediction"],
        "slices": {"regime": ["high-logp", "other"]},
        "public_validation": {
            key: context[key] for key in ("model", "dataset", "evaluator_relationship")
        },
    }


def _finite_number(value):
    return (
        isinstance(value, (int, float))
        and not isinstance(value, bool)
        and math.isfinite(value)
    )


def _count_description(observations, units):
    def count(value):
        return str(value) if isinstance(value, int) and value >= 0 else "unavailable"

    return f"{count(observations)} observations; {count(units)} connectivity units"


def _limit_description(label, observed, limit, *, counts=None):
    suffix = f" ({counts})" if counts else ""
    if not _finite_number(observed):
        return (
            f"{label}: unavailable; predeclared limit {limit:.6f}{suffix}: investigate."
        )
    passed = observed <= limit
    return (
        f"{label}: {observed:.6f} {'meets' if passed else 'exceeds'} "
        f"the predeclared limit {limit:.6f}{suffix}: "
        f"{'pass' if passed else 'fail'}."
    )


def write_decision_page(public, protocol):
    """Explain approved aggregates using the public, frozen case rules only."""
    public = Path(public)
    evaluations = {
        name: json.loads((public / (name + ".json")).read_text(encoding="utf-8"))[
            "shareable"
        ]["evaluation"]
        for name in ("reference-candidate", "proxy-candidate", "proxy-baseline")
    }
    original = evaluations["reference-candidate"]
    proxy = evaluations["proxy-candidate"]
    mean = evaluations["proxy-baseline"]
    paired = json.loads((public / "proxy-paired.json").read_text(encoding="utf-8"))[
        "shareable"
    ]
    if any(
        artifact.get("protocol", {}).get("sha256") != protocol.sha256
        for artifact in (*evaluations.values(), paired)
    ):
        raise ValueError("Decision rules must match the approved protocol digest")
    rules = protocol.as_dict()
    metric_rules = rules["quality_gate"]["metric"]["mae"]
    critical_rule = rules["quality_gate"]["slices"]["critical"]["high_logp"]
    practical_threshold = rules["comparison"]["practical_threshold"]
    critical = (
        proxy.get("slices", {})
        .get(critical_rule["column"], {})
        .get(critical_rule["value"], {})
    )
    critical_mae = (
        critical.get("metrics", {}).get(critical_rule["metric"])
        if critical.get("status") == "evaluated"
        else None
    )
    uncertainty = proxy.get("uncertainty", {})
    mae_interval = uncertainty.get("metrics", {}).get("mae", {})
    interval_upper = (
        mae_interval.get("upper")
        if uncertainty.get("status") == mae_interval.get("status") == "evaluated"
        else None
    )
    description = (
        proxy.get("external_validation", {})
        .get("dataset", {})
        .get("provenance_statement", "Approved aggregate Caco2 evaluation.")
    )
    overall_counts = _count_description(
        proxy.get("sample_counts", {}).get("n_samples"),
        uncertainty.get("n_independent_units"),
    )
    critical_counts = _count_description(
        critical.get("n"), critical.get("n_independent_units")
    )

    def metric_cell(evaluation):
        metric = evaluation.get("metrics", {}).get("mae")
        return f"{metric:.6f}" if _finite_number(metric) else "unavailable"

    improvement = paired.get("improvement_a_over_b")
    improvement_text = (
        f"{improvement:.6f}" if _finite_number(improvement) else "unavailable"
    )
    paired_interval = paired.get("paired_interval", {})
    lower, upper = paired_interval.get("lower"), paired_interval.get("upper")
    if (
        paired_interval.get("status") == "evaluated"
        and _finite_number(lower)
        and _finite_number(upper)
    ):
        meets_criterion = (
            lower >= practical_threshold if practical_threshold > 0 else lower > 0
        )
        relative = "meets" if meets_criterion else "does not meet"
        criterion = "at least" if practical_threshold > 0 else "greater than"
        interval_text = (
            f"Paired interval: [{lower:.6f}, {upper:.6f}]; its lower bound "
            f"{relative} the predeclared practical improvement criterion "
            f"({criterion} {practical_threshold:.6f})."
        )
    else:
        interval_text = (
            "Paired interval unavailable: relative improvement requires investigation."
        )
    lines = [
        "# Controlled Caco2 model-selection result",
        "",
        description,
        "",
        "| Evaluation | MAE | Quality |",
        "| --- | ---: | --- |",
        f"| Original held-out candidate | {metric_cell(original)} | {original.get('quality_gate', {}).get('status')} |",
        f"| Synthetic proxy candidate | {metric_cell(proxy)} | {proxy.get('quality_gate', {}).get('status')} |",
        f"| Synthetic proxy training mean | {metric_cell(mean)} | {mean.get('quality_gate', {}).get('status')} |",
        "",
        _limit_description(
            "Overall proxy MAE",
            proxy.get("metrics", {}).get("mae"),
            metric_rules["max"],
            counts=overall_counts,
        ),
        "",
        _limit_description(
            "Overall proxy MAE interval upper bound",
            interval_upper,
            metric_rules["max_ci_upper"],
        ),
        "",
        _limit_description(
            "Critical high-logP group MAE",
            critical_mae,
            critical_rule["max"],
            counts=critical_counts,
        ),
        "",
        f"Paired improvement of candidate over baseline: {improvement_text}. Model A is the forest reference; Model B is the training-mean reference. Predeclared practical improvement threshold: {practical_threshold:.6f}.",
        "",
        interval_text,
        "",
        "Relative improvement does not waive an overall or critical-group quality failure. Limits come from the public frozen case protocol; model-quality and aggregate-release decisions are separate.",
        "",
        "Reference/current changes reuse public compounds and IDs; independent-cohort delta intervals are withheld. Connectivity clusters are an inferential assumption, not proof of chemical independence.",
        "",
        "The signed files authenticate a pinned example issuer's statement. Execution and scientific validity are not independently verified. Raw rows, model parameters, keys, full audit evidence, and paths remain under local/.",
    ]
    path = public / "decision.md"
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path


def evaluate_case(
    output, reference, current, training, model_payloads, provenance, *, fixture=False
):
    output = Path(output).resolve()
    if output.exists() and any(output.iterdir()):
        raise ValueError("Choose an empty case-study output directory")
    private = output / "local"
    public = output / "approved"
    private.mkdir(parents=True)
    public.mkdir()
    training = training.copy()
    training["eligible"] = True
    reference, current = reference.copy(), current.copy()
    fit_entities = set(training.molecule_unit)
    for frame in (reference, current):
        frame["eligible"] = ~frame.molecule_unit.isin(fit_entities)
    training_path = private / "training-reference.csv"
    atomic_write_csv(training_path, training)
    reference_path, current_path = private / "reference.csv", private / "proxy.csv"
    atomic_write_csv(reference_path, reference)
    atomic_write_csv(current_path, current)
    baseline = current.copy()
    baseline["prediction"] = baseline.baseline
    baseline_path = private / "proxy-baseline.csv"
    atomic_write_csv(baseline_path, baseline)
    protocol = case_protocol(fixture=fixture)
    protocol_path = private / "protocol.yaml"
    protocol_path.write_text(yaml.safe_dump(protocol.as_dict(), sort_keys=False))
    models = {
        name: _model_info(private, name, payload)
        for name, payload in model_payloads.items()
    }
    reports = {}
    for name, source, model_key, diagnostics in (
        ("reference-candidate", reference_path, "caco2-rf-reference", False),
        ("proxy-candidate", current_path, "caco2-rf-reference", True),
        ("proxy-baseline", baseline_path, "caco2-training-mean", False),
    ):
        folder = private / name
        context = _context(
            models[model_key],
            provenance,
            (
                "synthetic_measurement_shift_proxy"
                if name.startswith("proxy")
                else "original_public_holdout"
            ),
        )
        settings = {
            "project": name,
            "protocol": str(protocol_path),
            "protocol_sha256": protocol.sha256,
            "input": {
                "path": str(source),
                "target_column": "target",
                "prediction_column": "prediction",
                "sample_id_column": "sample_id",
                "slice_columns": ["regime"],
                **(
                    {"baseline_prediction_column": "baseline"}
                    if model_key == "caco2-rf-reference"
                    else {}
                ),
            },
            "external_validation": context,
            "design_audit": {
                "training_reference": str(training_path),
                "reference_complete": True,
                "failure_mode": "stop",
            },
            "release": _release(context),
            "report": {
                "json": str(folder / "evaluation.json"),
                "markdown": str(folder / "evaluation.md"),
                "manifest": str(folder / "evaluation_manifest.json"),
            },
            "audit": {"path": str(folder / "audit.jsonl")},
        }
        if diagnostics:
            settings["diagnostics"] = {
                "reference_path": str(reference_path),
                "independent_cohorts": False,
                "practical_thresholds": {"mae": PRACTICAL_IMPROVEMENT},
            }
        config = private / (name + ".yaml")
        config.write_text(yaml.safe_dump(settings, sort_keys=False))
        summary = run_config(str(config))
        reports[name] = summary
        source_receipt = folder / "evaluation_receipt.shareable.json"
        if not source_receipt.exists():
            raise ValueError(
                "Case publication blocked; inspect local release/design audit before sharing"
            )
        (public / (name + ".json")).write_bytes(source_receipt.read_bytes())
    comparison_policy = {
        key: value
        for key, value in _release(
            _context(
                models["caco2-rf-reference"],
                provenance,
                "synthetic_measurement_shift_proxy",
            )
        ).items()
        if key
        not in {
            "public_validation",
            "include_degradation",
            "public_shift_features",
            "include_quality_gate",
        }
    }
    compared = compare_prediction_files(
        str(current_path),
        str(baseline_path),
        target="target",
        prediction_column="prediction",
        prediction_columns=None,
        sample_id_column="sample_id",
        task_type=None,
        class_labels=None,
        slice_columns=None,
        model_a_name="caco2-rf-reference",
        model_b_name="caco2-training-mean",
        **{name: None for name in PairedComparisonConfig.__dataclass_fields__},
        markdown_path=str(private / "paired.md"),
        json_path=str(private / "paired.json"),
        signing_secret=None,
        release_policy=comparison_policy,
        protocol=str(protocol_path),
        design_audit_options={
            "training_reference": str(training_path),
            "reference_complete": True,
            "failure_mode": "stop",
        },
    )
    compared_public = private / "paired.shareable.json"
    if not compared_public.exists():
        raise ValueError("Paired aggregate publication blocked; inspect local audit")
    (public / "proxy-paired.json").write_bytes(compared_public.read_bytes())
    from cryptography.hazmat.primitives import serialization
    from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey

    key = Ed25519PrivateKey.generate()
    key_path = private / "example-signing-key.pem"
    key_path.write_bytes(
        key.private_bytes(
            serialization.Encoding.PEM,
            serialization.PrivateFormat.PKCS8,
            serialization.NoEncryption(),
        )
    )
    key_path.chmod(0o600)
    public_key = base64.b64encode(
        key.public_key().public_bytes(
            serialization.Encoding.Raw, serialization.PublicFormat.Raw
        )
    ).decode()
    trust = {
        "schema_version": "receipt-trust-store/v1",
        "keys": {
            "caco2-case-example-v1": {
                "signer_id": "caco2-case-example",
                "public_key": public_key,
            }
        },
    }
    (public / "trust-store.yaml").write_text(yaml.safe_dump(trust, sort_keys=False))
    verification = {}
    for path in public.glob("*.json"):
        payload = json.loads(path.read_text())
        signer = {
            "signer_id": "caco2-case-example",
            "key_id": "caco2-case-example-v1",
            "private_key": str(key_path),
        }
        if path.stem != "proxy-paired":
            signer["model"] = {
                key: models[
                    (
                        "caco2-training-mean"
                        if path.stem == "proxy-baseline"
                        else "caco2-rf-reference"
                    )
                ][key]
                for key in ("id", "revision")
            }
        signed = sign_artifact(payload, signer)
        atomic_write_json(path, signed)
        checked = verify_payload(
            signed,
            trust_store=trust,
            require_trusted_signer=True,
            expected_protocol_sha256=protocol.sha256,
        )
        if not checked["valid"] or checked["execution_verified"] is not False:
            raise ValueError("Example receipt trust check failed")
        verification[path.name] = {
            key: checked[key]
            for key in (
                "valid",
                "hash_valid",
                "signature_valid",
                "signer_trusted",
                "protocol_bound",
                "evidence_level",
                "execution_verified",
            )
        }
    atomic_write_json(private / "provenance.json", provenance)
    write_decision_page(public, protocol)
    atomic_write_json(
        public / "verification.json",
        {
            "schema_version": "case-study-verification/v1",
            "example_issuer_only": True,
            "artifacts": verification,
            "independent_researcher_trials_completed": 0,
        },
    )
    return {
        "protocol": protocol,
        "reports": reports,
        "comparison": compared,
        "public_dir": public,
        "verification": verification,
    }


def prepare_tdc(cache, *, download=False):
    from rdkit import Chem
    from rdkit.Chem import Crippen
    from sklearn.ensemble import RandomForestRegressor
    from tdc import Evaluator
    from tdc.benchmark_group import admet_group

    from privatelabbench.integrations.tdc import (
        download_benchmarks,
        load_benchmark,
        partition_table,
    )
    from scripts.validate_tdc_admet import fingerprints

    if download:
        download_benchmarks(cache)
    snapshot = load_benchmark(cache, "caco2_wang")
    group = admet_group(path=str(Path(cache).resolve()))
    train, valid = group.get_train_valid_split(
        seed=1, benchmark="caco2_wang", split_type="default"
    )
    forest = RandomForestRegressor(
        n_estimators=128,
        min_samples_leaf=2,
        max_features="sqrt",
        random_state=1,
        n_jobs=1,
    )
    forest.fit(fingerprints(train.Drug), train.Y.to_numpy())
    predicted = forest.predict(fingerprints(snapshot.test.Drug))
    mean = float(train.Y.mean())
    baseline = np.repeat(mean, len(predicted))
    expected = float(Evaluator(name="mae")(snapshot.test.Y.to_numpy(), predicted))
    from privatelabbench.eval.metrics import regression_metrics

    actual = regression_metrics(
        snapshot.test.Y.to_numpy(), predicted, metric_names=["mae"]
    )["mae"]
    if not np.isclose(actual, expected, rtol=0, atol=1e-12):
        raise AssertionError("Official public metric parity failed")

    def unit(smiles):
        molecule = Chem.MolFromSmiles(str(smiles))
        if molecule is None:
            raise ValueError("The frozen case never drops invalid structures silently")
        return sha256(
            Chem.MolToSmiles(molecule, isomericSmiles=False).encode()
        ).hexdigest()

    reference = partition_table(
        snapshot.test, snapshot.task, "test", predictions=predicted
    )
    reference["baseline"] = baseline
    reference["molecule_unit"] = [unit(smiles) for smiles in reference.smiles]
    reference["regime"] = [
        (
            "high-logp"
            if Crippen.MolLogP(Chem.MolFromSmiles(str(smiles))) >= LOGP_THRESHOLD
            else "other"
        )
        for smiles in reference.smiles
    ]
    current = reference.copy()
    current["target"] = current.target + np.where(
        current.regime == "high-logp", PROXY_OFFSET, 0.0
    )
    training = pd.DataFrame(
        {
            "sample_id": [f"fit-{index:06d}" for index in range(len(train))],
            "molecule_unit": [unit(smiles) for smiles in train.Drug],
        }
    )
    trees = [
        {
            "children_left": tree.tree_.children_left.tolist(),
            "children_right": tree.tree_.children_right.tolist(),
            "feature": tree.tree_.feature.tolist(),
            "threshold": tree.tree_.threshold.tolist(),
            "value": tree.tree_.value[:, 0, 0].tolist(),
        }
        for tree in forest.estimators_
    ]
    models = {
        "caco2-rf-reference": {
            "schema_version": "numeric-forest-snapshot/v1",
            "preprocessing": {"morgan_radius": 2, "bits": 2048, "chirality": False},
            "seed": 1,
            "trees": trees,
        },
        "caco2-training-mean": {
            "schema_version": "constant-model-snapshot/v1",
            "prediction": mean,
        },
    }
    provenance = {
        "data_provenance": "public_benchmark_with_synthetic_measurement_shift",
        "description": "Original official public Caco2 holdout plus a synthetic +0.8 target-scale offset for MolLogP>=3.0; same compounds/IDs, not new private lab data or independent cohorts.",
        "training_records": len(train),
        "unused_validation_records": len(valid),
        "full_public_test_records": len(reference),
        "official_candidate_mae": actual,
        "upstream_candidate_mae": expected,
        "parity_absolute_error": abs(actual - expected),
        "official_baseline_mae": float(
            Evaluator(name="mae")(snapshot.test.Y.to_numpy(), baseline)
        ),
        "train_val_sha256": snapshot.task.train_val_sha256,
        "test_sha256": snapshot.task.test_sha256,
        "versions": {
            name: version(name)
            for name in ("PyTDC", "numpy", "pandas", "scikit-learn", "rdkit-pypi")
        },
        "analysis_plan": "docs/case_study/analysis_plan.md",
        "proxy_offset": PROXY_OFFSET,
        "logp_threshold": LOGP_THRESHOLD,
    }
    return reference, current, training, models, provenance


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cache-dir", type=Path, default=Path("outputs/tdc"))
